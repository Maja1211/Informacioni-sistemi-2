DROP TABLE IF EXISTS DIM_VREME;
CREATE TABLE DIM_VREME (
    IdVre INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    DatumVreme DATETIME NOT NULL UNIQUE,
    Dan INT NOT NULL,
    Mesec INT NOT NULL,
    Godina INT NOT NULL
);

DROP TABLE IF EXISTS DIM_MESTO;
CREATE TABLE DIM_MESTO (
    IdMes INT NOT NULL PRIMARY KEY,
    Naziv VARCHAR(100) NOT NULL
);

DROP TABLE IF EXISTS DIM_KATEGORIJA;
CREATE TABLE DIM_KATEGORIJA (
    IdKat INT NOT NULL PRIMARY KEY,
    Naziv VARCHAR(100) NOT NULL
);

DROP TABLE IF EXISTS DIM_KORISNIK;
CREATE TABLE DIM_KORISNIK (
    IdKor INT NOT NULL PRIMARY KEY,
    Pol CHAR(1) NOT NULL,
    Uzrast VARCHAR(20) NOT NULL,
    IdMes INT NOT NULL,
    FOREIGN KEY (IdMes) REFERENCES DIM_MESTO(IdMes)
);

DROP TABLE IF EXISTS DIM_ARTIKAL;
CREATE TABLE DIM_ARTIKAL (
    IdArt INT NOT NULL PRIMARY KEY,
    Naziv VARCHAR(100) NOT NULL,
    IdKat INT NOT NULL,
    FOREIGN KEY (IdKat) REFERENCES DIM_KATEGORIJA(IdKat)
);



DROP TABLE IF EXISTS FAKT_PRODAJA;
CREATE TABLE FAKT_PRODAJA (
    IdVre INT NOT NULL,
    IdKat INT NOT NULL,
    IdKorKupac INT NOT NULL,
    IdMesKupac INT NOT NULL,
    IdMesProdavac INT NOT NULL,
    Kolicina INT NOT NULL,
    Iznos DECIMAL(10,2) NOT NULL,

    PRIMARY KEY (IdVre, IdKat, IdKorKupac, IdMesKupac, IdMesProdavac),

    FOREIGN KEY (IdVre) REFERENCES DIM_VREME(IdVre),
    FOREIGN KEY (IdKat) REFERENCES DIM_KATEGORIJA(IdKat),
    FOREIGN KEY (IdKorKupac) REFERENCES DIM_KORISNIK(IdKor),
    FOREIGN KEY (IdMesKupac) REFERENCES DIM_MESTO(IdMes),
    FOREIGN KEY (IdMesProdavac) REFERENCES DIM_MESTO(IdMes)
);

DROP TABLE IF EXISTS FAKT_RECENZIJA;
CREATE TABLE FAKT_RECENZIJA (
    IdVre INT NOT NULL,
    IdArt INT NOT NULL,
    IdKorKupac INT NOT NULL,
    IdMesKupac INT NOT NULL,
    IdKorProdavac INT NOT NULL,
    IdMesProdavac INT NOT NULL,
    IdKat INT NOT NULL,
    Ocena DECIMAL(3,1) NOT NULL,

    PRIMARY KEY (IdVre, IdArt, IdKorKupac, IdKorProdavac, IdMesKupac, IdMesProdavac, IdKat),

    FOREIGN KEY (IdVre) REFERENCES DIM_VREME(IdVre),
    FOREIGN KEY (IdArt) REFERENCES DIM_ARTIKAL(IdArt),
    FOREIGN KEY (IdKorKupac) REFERENCES DIM_KORISNIK(IdKor),
    FOREIGN KEY (IdMesKupac) REFERENCES DIM_MESTO(IdMes),
    FOREIGN KEY (IdKorProdavac) REFERENCES DIM_KORISNIK(IdKor),
    FOREIGN KEY (IdMesProdavac) REFERENCES DIM_MESTO(IdMes),
    FOREIGN KEY (IdKat) REFERENCES DIM_KATEGORIJA(IdKat)
);
