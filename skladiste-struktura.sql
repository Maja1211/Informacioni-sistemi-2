CREATE SCHEMA IF NOT EXISTS skladiste;
USE skladiste;

DROP TABLE IF EXISTS POSLEDNJE_PUNJENJE;
CREATE TABLE POSLEDNJE_PUNJENJE (
    Id INT NOT NULL PRIMARY KEY,
    DatumVreme DATETIME NOT NULL
);

