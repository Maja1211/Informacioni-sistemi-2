CREATE SCHEMA IF NOT EXISTS operativna_baza_podataka;
USE operativna_baza_podataka;

DROP TABLE IF EXISTS MESTO;
CREATE TABLE MESTO (
    IdMes INT NOT NULL PRIMARY KEY,
    Naziv VARCHAR(100) NOT NULL
);

DROP TABLE IF EXISTS KORISNIK;
CREATE TABLE KORISNIK (
    IdKor INT NOT NULL PRIMARY KEY,
    Ime VARCHAR(100) NOT NULL,
    Prezime VARCHAR(100) NOT NULL,
    Mobilni VARCHAR(20) NOT NULL,
    Email VARCHAR(100) NOT NULL UNIQUE,
    Godiste INT NOT NULL,
    Pol CHAR(1) NOT NULL,
    IdMes INT NOT NULL,
    DatumKreiranja DATETIME NOT NULL,
    FOREIGN KEY (IdMes) REFERENCES MESTO(IdMes)
);

DROP TABLE IF EXISTS KATEGORIJA;
CREATE TABLE KATEGORIJA (
    IdKat INT NOT NULL PRIMARY KEY,
    Naziv VARCHAR(100) NOT NULL,
    DatumKreiranja DATETIME NOT NULL
);

DROP TABLE IF EXISTS ARTIKAL;
CREATE TABLE ARTIKAL (
    IdArt INT NOT NULL PRIMARY KEY,
    Naziv VARCHAR(100) NOT NULL,
    Opis TEXT,
    Cena DECIMAL(10,2) NOT NULL,
    Popust DECIMAL(5,2) NOT NULL,
    Kolicina INT NOT NULL,
    IdKor INT NOT NULL,      
    IdKat INT NOT NULL,
    DatumKreiranja DATETIME NOT NULL,
    FOREIGN KEY (IdKor) REFERENCES KORISNIK(IdKor),
    FOREIGN KEY (IdKat) REFERENCES KATEGORIJA(IdKat)
);

DROP TABLE IF EXISTS NARUDZBINA;
CREATE TABLE NARUDZBINA (
    IdNar INT NOT NULL PRIMARY KEY,
    IdKor INT NOT NULL,      
    Datum DATE NOT NULL,
    Vreme TIME NOT NULL,
    Iznos DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (IdKor) REFERENCES KORISNIK(IdKor)
);

DROP TABLE IF EXISTS STAVKA;
CREATE TABLE STAVKA (
    IdNar INT NOT NULL,
    IdArt INT NOT NULL,
    Iznos DECIMAL(10,2) NOT NULL,
    Kolicina INT NOT NULL,
    PRIMARY KEY (IdNar, IdArt),
    FOREIGN KEY (IdNar) REFERENCES NARUDZBINA(IdNar),
    FOREIGN KEY (IdArt) REFERENCES ARTIKAL(IdArt)
);

DROP TABLE IF EXISTS KORPA;
CREATE TABLE KORPA (
    IdKor INT NOT NULL,
    IdArt INT NOT NULL,
    Kolicina INT NOT NULL,
    PRIMARY KEY (IdKor, IdArt),
    FOREIGN KEY (IdKor) REFERENCES KORISNIK(IdKor),
    FOREIGN KEY (IdArt) REFERENCES ARTIKAL(IdArt)
);


DROP TABLE IF EXISTS RECENZIJA;
CREATE TABLE RECENZIJA (
    IdKor INT NOT NULL,      
    IdArt INT NOT NULL,
    Ocena DECIMAL(3,1) NOT NULL,
    Opis TEXT,
    Datum DATE NOT NULL,
    Vreme TIME NOT NULL,
    PRIMARY KEY (IdKor, IdArt),
    FOREIGN KEY (IdKor) REFERENCES KORISNIK(IdKor),
    FOREIGN KEY (IdArt) REFERENCES ARTIKAL(IdArt)
);
